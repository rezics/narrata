//! Rebuilds the frozen first-party VN source, pack and choice-safe-point checkpoint.

use std::{
    collections::BTreeMap,
    env,
    error::Error,
    fs,
    path::{Path, PathBuf},
    sync::Arc,
};

use narrata_kernel::codec::sha256;
use narrata_nodes::{
    ExecutionId, NodeRegistry, PackageSource, Program, ProjectManifest, ProjectSource, Session,
    compile, view::Interaction,
};
use serde_json::Value;

fn main() -> Result<(), Box<dyn Error>> {
    let mut args = env::args_os().skip(1);
    let source_path = args
        .next()
        .map(PathBuf::from)
        .ok_or("usage: emit_vn_compat <source.json> <output-directory>")?;
    let output = args
        .next()
        .map(PathBuf::from)
        .ok_or("usage: emit_vn_compat <source.json> <output-directory>")?;
    if args.next().is_some() {
        return Err("usage: emit_vn_compat <source.json> <output-directory>".into());
    }

    let source_bytes = fs::read(&source_path)?;
    let host_path = source_path
        .parent()
        .unwrap_or(Path::new("."))
        .join("host-fixture.json");
    let host_bytes = fs::read(host_path)?;
    let source_json: Value = serde_json::from_slice(&source_bytes)?;
    let manifest: ProjectManifest = serde_json::from_value(source_json["manifest"].clone())?;
    let package: PackageSource = serde_json::from_value(source_json["package"].clone())?;
    let source = ProjectSource {
        manifest,
        packages: BTreeMap::from([("main".to_owned(), package)]),
    };
    let compilation = compile(&source, &NodeRegistry::visual_novel())?;
    let names = compilation.names.clone();
    let (program, _) = Program::from_pack(&compilation.pack)?;
    let execution: ExecutionId = "execution:0190f2a0000070008000000000000001".parse()?;
    let mut session = Session::new(Arc::new(program), execution)?;

    loop {
        let view = session.view(Some(&names))?;
        match view.interaction {
            Interaction::Advance { line, .. } if line.unit.key.as_str() == "dialogue.four" => break,
            Interaction::Advance { dialogue, .. } => {
                session.advance(&view.cursor, dialogue)?;
            }
            Interaction::Choose {
                choice_point,
                options,
                ..
            } => {
                let left = options
                    .iter()
                    .find(|option| option.key.as_deref() == Some("left"))
                    .ok_or("the source no longer offers the left branch")?;
                session.choose(&view.cursor, choice_point, vec![left.id])?;
            }
            Interaction::Finished { .. } => {
                return Err("the source finished before the fourth dialogue line".into());
            }
        }
    }

    fs::create_dir_all(&output)?;
    let export_bytes = session.export()?.into_bytes();
    let view_bytes = serde_json::to_vec_pretty(&session.view(Some(&names))?)?;
    let mut artifacts = BTreeMap::new();
    for (name, bytes) in [
        ("host-fixture.json", host_bytes.as_slice()),
        ("save.export.json", export_bytes.as_slice()),
        ("source.json", source_bytes.as_slice()),
        ("story.narpack", compilation.pack.as_slice()),
        ("view.json", view_bytes.as_slice()),
    ] {
        artifacts.insert(
            name,
            serde_json::json!({"sha256": hex::encode(sha256(bytes))}),
        );
        fs::write(output.join(name), bytes)?;
    }
    let manifest = serde_json::json!({
        "corpus_version": 1,
        "format": "ADR 0024 VN0 source format 3, object schema 2 and restorable scene targets",
        "artifact_id": compilation.program.artifact_id().to_string(),
        "execution": execution.to_string(),
        "build_provenance": {
            "story.narpack": "cargo run -p narrata-node-tools --example emit_vn_compat -- <source.json> <output-directory>",
            "save.export.json": "generated by advancing the first three dialogue lines and choosing left",
            "view.json": "generated at the restored fourth dialogue line; bodies and media are resolved only by host-fixture.json"
        },
        "checkpoint": "save.export.json restores at dialogue.four after the left branch; the earlier choice can be checked out and the right branch replayed",
        "artifacts": artifacts
    });
    fs::write(
        output.join("manifest.json"),
        serde_json::to_vec_pretty(&manifest)?,
    )?;
    Ok(())
}
