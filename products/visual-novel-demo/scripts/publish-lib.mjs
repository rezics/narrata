import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

/** Runs the reference VN's checked format-3 build path and writes its immutable host objects. */
export async function publishReferenceVn({ authoring, sourceDirectory, packPath, publicStoryDirectory, generatedPublicationPath }) {
  const manifest = JSON.parse(readFileSync(resolve(sourceDirectory, "project.json"), "utf8"));
  const alias = manifest.product.entry.package;
  const packagePath = manifest.packages[alias];
  if (typeof packagePath !== "string") throw new Error(`The VN entry package ${alias} is missing from the manifest.`);
  const source = JSON.parse(readFileSync(resolve(sourceDirectory, packagePath), "utf8"));
  const split = authoring.splitVnSource(manifest, [[alias, source]]);
  if (!split.complete || split.diagnostics.some(item => item.severity === "error")) {
    throw new Error(`The VN source records are invalid: ${JSON.stringify(split.diagnostics)}`);
  }

  const drafts = authoring.createVnDrafts();
  let candidate;
  try {
    for (const record of split.records) drafts.add(record.bytes);
    const checked = drafts.check();
    if (!checked.complete || checked.diagnostics.some(item => item.severity === "error")) {
      throw new Error(`The VN source is invalid: ${JSON.stringify(checked.diagnostics)}`);
    }
    candidate = drafts.preview();
    if (!candidate.compiled || !candidate.report.artifact_id) {
      throw new Error(`The VN preview failed: ${JSON.stringify(candidate.report.diagnostics)}`);
    }
    const artifactId = candidate.report.artifact_id;
    const pack = candidate.pack();
    const lock = candidate.report.lock;
    if (!lock) throw new Error("The checked VN candidate omitted its composition lock.");
    mkdirSync(dirname(packPath), { recursive: true });
    writeFileSync(packPath, pack);

    const parts = splitPack(pack);
    const artifactFolder = artifactId.slice("artifact:".length);
    const versioned = join(publicStoryDirectory, artifactFolder);
    const objectDirectory = join(versioned, "objects");
    mkdirSync(objectDirectory, { recursive: true });
    writeImmutable(join(versioned, "manifest.cbor"), parts.manifest);
    writeImmutable(join(versioned, "project.lock.json"), Buffer.from(`${JSON.stringify(lock, null, 2)}\n`));
    const objects = [...parts.objects].map(([id, bytes]) => {
      writeImmutable(join(objectDirectory, `${id.slice("object:".length)}.cbor`), bytes);
      return { id, bytes: bytes.byteLength, sha256: createHash("sha256").update(bytes).digest("hex") };
    }).sort((left, right) => left.id.localeCompare(right.id));

    const manifestPath = `/story/${artifactFolder}/manifest.cbor`;
    const objectUrlDirectory = `/story/${artifactFolder}/objects`;
    mkdirSync(dirname(generatedPublicationPath), { recursive: true });
    writeFileSync(generatedPublicationPath, [
      "// Generated by products/visual-novel-demo/scripts/publish.mjs from the public VN authoring candidate.",
      `export const vnDemoArtifactId = ${JSON.stringify(artifactId)} as const;`,
      `export const vnDemoManifestPath = ${JSON.stringify(manifestPath)} as const;`,
      `export const vnDemoObjectDirectory = ${JSON.stringify(objectUrlDirectory)} as const;`,
      "",
    ].join("\n"));
    return { artifact_id: artifactId, lock, objects, manifest: manifestPath, pack };
  } finally {
    candidate?.free();
    drafts.free();
  }
}

function splitPack(bytes) {
  const pack = Buffer.from(bytes);
  let offset = 56;
  function size(major) {
    const head = pack.readUInt8(offset++);
    if (head >> 5 !== major) throw new Error("Unexpected VN pack encoding.");
    const info = head & 31;
    if (info < 24) return info;
    const width = info === 24 ? 1 : info === 25 ? 2 : info === 26 ? 4 : 0;
    if (!width) throw new Error("Unsupported VN pack size encoding.");
    const value = pack.readUIntBE(offset, width);
    offset += width;
    return value;
  }
  function object() {
    const length = size(2);
    const value = pack.subarray(offset, offset + length);
    if (value.byteLength !== length) throw new Error("Truncated VN pack object.");
    offset += length;
    return new Uint8Array(value);
  }
  if (size(5) !== 4 || size(0) !== 0) throw new Error("Unexpected VN pack map.");
  const manifest = object();
  if (size(0) !== 1) throw new Error("Missing VN program chunks.");
  const chunks = Array.from({ length: size(4) }, object);
  if (size(0) !== 2) throw new Error("Missing VN tombstones.");
  const tombstones = object();
  if (size(0) !== 3) throw new Error("Missing VN names table.");
  object();
  if (offset !== pack.length) throw new Error("Trailing bytes in the VN pack.");
  const entries = [...chunks, tombstones].map(bytes => [objectId(bytes), bytes]);
  if (new Set(entries.map(([id]) => id)).size !== entries.length) throw new Error("Duplicate VN object identity.");
  return { manifest, objects: entries };
}

function objectId(envelope) {
  const bytes = Buffer.from(envelope);
  if (bytes.byteLength < 56) throw new Error("Truncated VN object envelope.");
  const digest = createHash("sha256").update("narrata-object\0").update(bytes.subarray(10, 14)).update(bytes.subarray(56)).digest("hex");
  return `object:${digest}`;
}

function writeImmutable(path, bytes) {
  try {
    const current = readFileSync(path);
    if (!current.equals(Buffer.from(bytes))) throw new Error(`Immutable VN object changed at ${path}.`);
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
      writeFileSync(path, bytes);
      return;
    }
    throw error;
  }
}
