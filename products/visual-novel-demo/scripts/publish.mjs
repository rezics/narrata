import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const product = resolve(root, "products/visual-novel-demo");
const packPath = resolve(product, "story.narpack");

const artifactId = execFileSync("cargo", [
  "run", "--quiet", "--locked", "-p", "narrata-node-tools", "--example", "emit_vn_demo", "--",
  resolve(product, "project.json"), resolve(product, "packages/main.json"), packPath,
], { cwd: root, encoding: "utf8" }).trim();
if (!/^artifact:[0-9a-f]{64}$/.test(artifactId)) {
  throw new Error("The compiled VN is missing an exact artifact identity.");
}

const parts = splitPack(readFileSync(packPath));
const artifactFolder = artifactId.slice("artifact:".length);
const publicStory = resolve(product, "public/story");
const versioned = join(publicStory, artifactFolder);
const objectDirectory = join(versioned, "objects");
mkdirSync(objectDirectory, { recursive: true });
writeImmutable(join(versioned, "manifest.cbor"), parts.manifest);
const objects = [...parts.objects].map(([id, bytes]) => {
  writeImmutable(join(objectDirectory, `${id.slice("object:".length)}.cbor`), bytes);
  return { id, bytes: bytes.byteLength, sha256: createHash("sha256").update(bytes).digest("hex") };
}).sort((left, right) => left.id.localeCompare(right.id));
const generated = resolve(root, "examples/visual-novel-web/src/generated/publication.ts");
mkdirSync(dirname(generated), { recursive: true });
const manifestPath = `/story/${artifactFolder}/manifest.cbor`;
const objectUrlDirectory = `/story/${artifactFolder}/objects`;
writeFileSync(generated, [
  "// Generated by products/visual-novel-demo/scripts/publish.mjs from the checked native VN pack.",
  `export const vnDemoArtifactId = ${JSON.stringify(artifactId)} as const;`,
  `export const vnDemoManifestPath = ${JSON.stringify(manifestPath)} as const;`,
  `export const vnDemoObjectDirectory = ${JSON.stringify(objectUrlDirectory)} as const;`,
  "",
].join("\n"));
