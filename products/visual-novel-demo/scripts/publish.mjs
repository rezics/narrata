function splitPack(bytes) {
  const pack = Buffer.from(bytes);
  let offset = 56;
  function size(major) {
    const head = pack.readUInt8(offset++);
    if (head >> 5 !== major) throw new Error("Unexpected VN pack encoding.");
    const info = head & 31;
    if (info < 24) return info;
    const width = info === 24 ? 1 : info === 25 ? 2 : info === 26 ? 4 : 0;
    if (!width) throw new Error("Unsupported VN pack size encoding.");
    const value = pack.readUIntBE(offset, width);
    offset += width;
    return value;
  }
  function object() {
    const length = size(2);
    const value = pack.subarray(offset, offset + length);
    if (value.byteLength !== length) throw new Error("Truncated VN pack object.");
    offset += length;
    return new Uint8Array(value);
  }
  if (size(5) !== 4 || size(0) !== 0) throw new Error("Unexpected VN pack map.");
  const manifest = object();
  if (size(0) !== 1) throw new Error("Missing VN program chunks.");
  const chunks = Array.from({ length: size(4) }, object);
  if (size(0) !== 2) throw new Error("Missing VN tombstones.");
  const tombstones = object();
  if (size(0) !== 3) throw new Error("Missing VN names table.");
  const names = object();
  if (offset !== pack.length) throw new Error("Trailing bytes in the VN pack.");
  const entries = [...chunks, tombstones].map(bytes => [objectId(bytes), bytes]);
  if (new Set(entries.map(([id]) => id)).size !== entries.length) throw new Error("Duplicate VN object identity.");
  return { manifest, names, objects: entries };
}

function objectId(envelope) {
  const bytes = Buffer.from(envelope);
  if (bytes.byteLength < 56) throw new Error("Truncated VN object envelope.");
  const digest = createHash("sha256").update("narrata-object\0").update(bytes.subarray(10, 14)).update(bytes.subarray(56)).digest("hex");
  return `object:${digest}`;
}

function writeImmutable(path, bytes) {
  try {
    const current = readFileSync(path);
    if (!current.equals(Buffer.from(bytes))) throw new Error(`Immutable VN object changed at ${path}.`);
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
      writeFileSync(path, bytes);
      return;
    }
    throw error;
  }
}
